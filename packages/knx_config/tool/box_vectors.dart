// Prints test vectors (frames of knx_core and the wire format of the box) for the firmware test:
// dart run tool/box_vectors.dart > ../../firmware/evoknx_box/test_host/vectors.h
import 'dart:convert';
import 'dart:io';

import 'package:knx_config/knx_config.dart';
import 'package:knx_core/knx_core.dart';

String hex(List<int> b) => b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();

void main() {
  final ga1 = GroupAddress.parse('1/1/5'), ga2 = GroupAddress.parse('2/0/1'), ga3 = GroupAddress.parse('3/4/200');
  final cemiReq = CemiFrame.groupRequest(ga1, TelegramType.write, KnxPayload.short(1)).toBytes();
  final cemiReq2 = CemiFrame.groupRequest(ga2, TelegramType.write, KnxPayload.bytes([0x80])).toBytes();
  final cemiReq3 = CemiFrame.groupRequest(ga3, TelegramType.write, Dpt.encode('9.001', 21.5)).toBytes();
  final cemiReq4 = CemiFrame.groupRequest(ga3, TelegramType.write, Dpt.encode('16.001', 'Hello')).toBytes();
  final ind =
      CemiFrame(messageCode: CemiCode.lDataInd, source: const IndividualAddress(0x1101), destination: ga1.raw, apci: Apci.write, data: [1], shortData: true)
          .toBytes();
  final indResp = CemiFrame(
          messageCode: CemiCode.lDataInd, source: const IndividualAddress(0x1102), destination: ga2.raw, apci: Apci.response, data: [0x80], shortData: false)
      .toBytes();
  final routing = KnxIpFrame.build(
      0x0530,
      CemiFrame(messageCode: CemiCode.lDataInd, source: const IndividualAddress(0xFFFA), destination: ga1.raw, apci: Apci.write, data: [0], shortData: true)
          .toBytes());
  final ip = InternetAddress('192.168.1.77');
  final conn = KnxIpFrame.connectRequest(Hpai(ip, 3671), Hpai(ip, 3671));
  final state = KnxIpFrame.connectionStateRequest(7, Hpai(ip, 3671));
  final disc = KnxIpFrame.disconnectRequest(7, Hpai(ip, 3671));
  final tun = KnxIpFrame.tunnellingRequest(7, 3, cemiReq);
  final ack = KnxIpFrame.tunnellingAck(7, 3, 0);
  final tunBody = tun;
  void c(String name, List<int> b) => print('static const char* $name = "${hex(b)}";');
  print('// Generated by packages/knx_config/tool/box_vectors.dart. Do not edit.');
  c('V_CEMI_REQ_SHORT', cemiReq);
  c('V_CEMI_REQ_1BYTE', cemiReq2);
  c('V_CEMI_REQ_FLOAT', cemiReq3);
  c('V_CEMI_REQ_TEXT', cemiReq4);
  c('V_CEMI_IND_SHORT', ind);
  c('V_CEMI_IND_RESP', indResp);
  c('V_ROUTING', routing);
  c('V_CONNECT', conn);
  c('V_STATE', state);
  c('V_DISCONNECT', disc);
  c('V_TUNNEL', tunBody);
  c('V_ACK', ack);

  final doc = newProject('Villa');
  doc['groupAddresses'] = [
    {'id': 'ga_1_1_5', 'address': '1/1/5', 'name': 'WC light', 'dpt': '1.001'},
    {'id': 'ga_2_0_1', 'address': '2/0/1', 'name': 'Garden pump', 'dpt': '1.001'},
  ];
  doc['box'] = {
    'added': true,
    'name': 'Villa box',
    'host': '192.168.1.60',
    'key': 'A' * 32,
    'bus': {'mode': 'tunnel', 'host': '192.168.1.50', 'port': 3671},
    'extra': [
      {'ga': 'ga_1_1_5', 'name': 'WC light'},
      {'ga': 'ga_2_0_1', 'name': 'Garden pump'},
    ],
  };
  final timers = [
    makeBoxTimer('schedule')
      ..['id'] = 'tm_a'
      ..['title'] = 'Night off'
      ..['tg'] = 'g:ga_1_1_5'
      ..['act'] = 'off'
      ..['time'] = '22:30'
      ..['days'] = [1, 2, 3, 4, 5],
    makeBoxTimer('schedule')
      ..['id'] = 'tm_b'
      ..['tg'] = 'g:ga_2_0_1'
      ..['act'] = 'on'
      ..['time'] = '6:05'
      ..['days'] = [6, 7],
    makeBoxTimer('countdown')
      ..['id'] = 'tm_c'
      ..['title'] = 'WC auto off'
      ..['wtg'] = 'g:ga_1_1_5'
      ..['wval'] = 'on'
      ..['secs'] = 600
      ..['tg'] = 'g:ga_1_1_5'
      ..['act'] = 'off',
  ];
  final wire = boxTimersWire(doc, timers);
  print('static const char* V_WIRE = R"JSON(${jsonEncode(wire)})JSON";');
  print('static const char* V_WIRE_REV = "${wire['rev']}";');
  print('static const char* V_SETTINGS = R"JSON(${jsonEncode(boxSettingsWire(doc, tzMinutes: 420))})JSON";');
}
